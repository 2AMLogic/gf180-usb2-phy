#!/usr/bin/env python3
"""Emit `klt sim` Monte Carlo requests for the single-ended D+/D- receiver rows.

Statistical row classified in spec/decisions/0007-analog-statistical-rows.md
(§4): the single-ended thresholds VIL < 0.8 V / VIH > 2.0 V depend on the
input-stage MOS mismatch, so the 45-corner matrix alone cannot validate them.
This script expresses the Monte Carlo campaign as `klt sim` requests
(`monte_carlo`, N samples per corner) that `KLT_SIM_BACKEND=batch` sends to the
Spot fleet. It only WRITES requests; it never dispatches and never runs
ngspice. It reuses `sim/diff-receiver-mc/build_requests.py` for the request
shape, so the two campaigns stay identical apart from the testbench.

For each of the two receivers (``dp``, ``dm``) two variants are written,
differing only in the deck's mismatch switch:

* ``mismatch`` -- ``sw_stat_mismatch = 1``: the measurement campaign.
* ``control``  -- ``sw_stat_mismatch = 0``: the deterministic negative control;
  every sigma must be exactly 0.

Limits are copied from each testbench's ``checks``; nothing is widened.

    python3 sim/se-receiver-mc/build_requests.py WORKDIR [--n N] [--seed S]
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SIM = HERE.parent
sys.path.insert(0, str(SIM))

from harness import testbench as tb_mod  # noqa: E402
from harness.pdk import find_pdk  # noqa: E402

_spec = importlib.util.spec_from_file_location(
    "diff_receiver_mc_build_requests", SIM / "diff-receiver-mc" / "build_requests.py"
)
base = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(base)

SOURCES = {
    "dp": SIM / "se-receiver-dp-thresholds",
    "dm": SIM / "se-receiver-dm-thresholds",
}
DEFAULT_N = base.DEFAULT_N
DEFAULT_SEED = base.DEFAULT_SEED
VARIANTS = base.VARIANTS


def build_deck(tb, pdk, sw_stat_mismatch: int, side: str) -> str:
    """Self-contained deck: the fleet stages only the request's netlist."""
    design = Path(pdk.design_include).read_text()
    return "\n".join([
        f"* se-receiver-mc ({side}) -- GENERATED by sim/se-receiver-mc/build_requests.py, do not edit",
        ".options wnflag=1",
        f".param vdd_nom={tb.nominal_supply_v!r}",
        f".param vdd_val={tb.nominal_supply_v!r}",
        ".param temp_c=27.0",
        "* ---- begin inlined design.ngspice (PDK) ----",
        base.strip_end(design).rstrip(),
        "* ---- end inlined design.ngspice ----",
        # after design.ngspice, which defaults it to 0.
        f".param sw_stat_mismatch = {sw_stat_mismatch}",
        "* ---- begin inlined DUT ----",
        base.strip_end(Path(tb.dut).read_text()).rstrip(),
        "* ---- end inlined DUT ----",
        "* ---- begin testbench fragment ----",
        base.strip_end(Path(tb.netlist).read_text()).rstrip(),
        "* ---- end testbench fragment ----",
        "",
    ])


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("workdir", type=Path)
    ap.add_argument("--n", type=int, default=DEFAULT_N, help="samples per corner point")
    ap.add_argument("--seed", type=int, default=DEFAULT_SEED)
    args = ap.parse_args(argv)

    pdk = find_pdk()
    for side, src in SOURCES.items():
        tb = tb_mod.load(src)
        manifest = json.loads((src / "testbench" / "tb.json").read_text())
        for variant, switch in VARIANTS.items():
            d = args.workdir / side / variant
            d.mkdir(parents=True, exist_ok=True)
            (d / "body.spice").write_text(build_deck(tb, pdk, switch, side))
            (d / "request.json").write_text(
                json.dumps(base.build_request(tb, pdk, manifest, args.n, args.seed), indent=2) + "\n"
            )
            print(f"wrote {d}/request.json (sw_stat_mismatch={switch}, n={args.n}, seed={args.seed})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
