#!/usr/bin/env python3
"""Emit `klt sim` Monte Carlo requests for the single-ended D+/D- receiver rows.

Statistical row classified in spec/decisions/0007-analog-statistical-rows.md
(§4): the single-ended thresholds VIL < 0.8 V / VIH > 2.0 V depend on the
input-stage MOS mismatch, so the 45-corner matrix alone cannot validate them.
This script expresses the Monte Carlo campaign as `klt sim` requests
(`monte_carlo`, N samples per corner) that `KLT_SIM_BACKEND=batch` sends to the
Spot fleet. It only WRITES requests; it never dispatches and never runs
ngspice. It reuses `sim/diff-receiver-mc/build_requests.py` for the request
shape, so the two campaigns stay identical apart from the testbench.

For each of the two receivers (``dp``, ``dm``) four variants are written,
differing only in the deck's mismatch switch:

* ``mismatch`` -- ``sw_stat_mismatch = 1``: the measurement campaign.
* ``control``  -- ``sw_stat_mismatch = 0``: the deterministic negative control;
  every sigma must be exactly 0.
* ``degraded`` / ``degraded_neg`` -- ``sw_stat_mismatch = 1`` plus a series DC
  offset of +/-``DEGRADED_OFFSET_V`` between the swept input and the receiver:
  the seeded known-bad variants `klt yield-samples --negative-control` needs
  (``control`` is better than nominal, so its yield cannot degrade). +offset
  pulls the threshold below VIL and breaks ``vth_v`` / ``out_at_vil``; -offset
  pushes it above VIH and breaks ``vth_v`` / ``out_at_vih``. Limits untouched.

Limits are copied from each testbench's ``checks``; nothing is widened.

    python3 sim/se-receiver-mc/build_requests.py WORKDIR [--n N] [--seed S]
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SIM = HERE.parent
sys.path.insert(0, str(SIM))

from harness import testbench as tb_mod  # noqa: E402
from harness.pdk import find_pdk  # noqa: E402

_spec = importlib.util.spec_from_file_location(
    "diff_receiver_mc_build_requests", SIM / "diff-receiver-mc" / "build_requests.py"
)
base = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(base)

SOURCES = {
    "dp": SIM / "se-receiver-dp-thresholds",
    "dm": SIM / "se-receiver-dm-thresholds",
}
DEFAULT_N = base.DEFAULT_N
DEFAULT_SEED = base.DEFAULT_SEED
# The ratified window is 0.8-2.0 V and the measured threshold sits at 1.2-1.5 V
# over the 45 corners, so the offset has to exceed the 0.5 V of margin to push
# samples out of limits (0.9 V leaves every corner out of limits).
DEGRADED_OFFSET_V = 0.9
# variant -> (sw_stat_mismatch, series offset on the input, volts)
VARIANTS = {
    "mismatch": (1, 0.0),
    "control": (0, 0.0),
    "degraded": (1, DEGRADED_OFFSET_V),
    "degraded_neg": (1, -DEGRADED_OFFSET_V),
}


def inject_offset(fragment: str, offset_v: float) -> str:
    """Put a series DC source between the swept input `IN` and the receiver."""
    out, n = [], 0
    for line in fragment.splitlines():
        m = re.match(r"^(Xrx\w+)\s+(VDD)\s+(0)\s+IN\s+(.*)$", line)
        if m:
            name, vdd, gnd, rest = m.groups()
            out.append(f"{name} {vdd} {gnd} INI {rest}")
            out.append(f"vos INI IN dc {offset_v!r}")
            n += 1
        else:
            out.append(line)
    if n != 1:
        raise SystemExit(f"inject_offset: expected one receiver instance on IN, found {n}")
    return "\n".join(out)


def build_deck(tb, pdk, sw_stat_mismatch: int, side: str, offset_v: float = 0.0) -> str:
    """Self-contained deck: the fleet stages only the request's netlist."""
    fragment = base.strip_end(Path(tb.netlist).read_text()).rstrip()
    if offset_v:
        fragment = inject_offset(fragment, offset_v)
    return base.assemble_deck(
        f"* se-receiver-mc ({side}) -- GENERATED by sim/se-receiver-mc/build_requests.py, do not edit",
        tb, pdk, sw_stat_mismatch, fragment,
    )


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("workdir", type=Path)
    ap.add_argument("--n", type=int, default=DEFAULT_N, help="samples per corner point")
    ap.add_argument("--seed", type=int, default=DEFAULT_SEED)
    ap.add_argument("--timeout-s", type=int, default=base.DEFAULT_TIMEOUT_S,
                    help="options.timeout_s per unit (size from a measured fleet pilot)")
    ap.add_argument("--variant", choices=sorted(VARIANTS), action="append",
                    help="write only this variant (repeatable); default all")
    args = ap.parse_args(argv)

    pdk = find_pdk()
    for side, src in SOURCES.items():
        tb = tb_mod.load(src)
        manifest = json.loads((src / "testbench" / "tb.json").read_text())
        for variant, (switch, offset_v) in VARIANTS.items():
            if args.variant and variant not in args.variant:
                continue
            d = args.workdir / side / variant
            d.mkdir(parents=True, exist_ok=True)
            (d / "body.spice").write_text(build_deck(tb, pdk, switch, side, offset_v))
            (d / "request.json").write_text(
                json.dumps(base.build_request(tb, pdk, manifest, args.n, args.seed, args.timeout_s), indent=2) + "\n"
            )
            print(f"wrote {d}/request.json (sw_stat_mismatch={switch}, offset={offset_v} V, n={args.n}, seed={args.seed})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
