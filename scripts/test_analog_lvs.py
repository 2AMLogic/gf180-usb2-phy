#!/usr/bin/env python3
"""Self-test for ``analog_lvs.py``: stream discovery, request shape, parsing.

These cases pin the contracts the harness's result depends on without
running klt or the PDK, so they run in CI:

  * **stream discovery** comes from the committed ``*.gds`` glob, never a
    hard-coded block list (#339 may merge the two single-ended receivers),
    is sorted, and is not confused by sibling files;
  * **a missing reference netlist fails loudly** before any tool runs,
    rather than silently skipping the block;
  * **the request shape** is the one the 2026-10-09 analog record
    established -- inline layout extraction with the ``gf180mcu`` deck
    against a ``subckt-call`` reference -- with bare relative filenames, and
    **no result-relaxing option** (no ``parameter_tolerance``, no
    ``compare_parameters``, no flattening);
  * **the SPICE parser** reads both dialects the harness meets (the
    schematic export's subcircuit calls and ``klt extract``'s M-cards),
    including continuation lines, and picks the body terminal off the right
    position -- the fact the cause analysis rests on;
  * **``classify``** does not mistake the ``ppolyf_u_1k`` poly resistor for a
    PFET on its leading "p";
  * **the cause analysis** reports the unnamed-net, port-set and bulk-net
    differences it claims to measure.

Usage:
    python3 scripts/test_analog_lvs.py        (or: python3 -m pytest scripts/test_analog_lvs.py)
Exit codes: 0 all cases behave as specified, 1 otherwise.
"""

from __future__ import annotations

import json
import os
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import analog_lvs as alvs  # noqa: E402


# A two-device excerpt in the schematic export's dialect: subcircuit calls,
# a continuation line, and the body terminal in fourth position.
REFERENCE_SPICE = """\
* demo -- generated by design/netlist.py
.subckt demo VDD VSS DP RXD
XRBIAS IBIASN VDD VSS ppolyf_u_1k r_width=2u r_length=400u m=1
XMN_IN RXD DP VSS VSS nfet_03v3 L=0.28u W=20u nf=1 ad='x' as='y'
+ pd='z' ps='w' nrd='0.18u / W' sa=0 sb=0 m=1
XMP_LOAD RXD IBIASN VDD VDD pfet_03v3 L=0.28u W=40u nf=1 m=1
.ends
"""

# The same circuit as `klt extract` writes it: M-cards for the MOSFETs, an
# X-card for the resistor, unnamed nets as `\$<n>`, bulk on the
# deck-synthesized `vsubs` / an anonymous well.
LAYOUT_SPICE = """\
* extracted by klt extract --deck gf180mcu
* cell demo
* pin VDD
.SUBCKT demo VDD RXD vsubs
* device instance $1 r0 *1 1.0,2.0 nfet
M$1 RXD \\$5 \\$1 vsubs nfet L=0.28U W=20U AS=1P PS=5U
* device instance $2 r0 *1 3.0,4.0 pfet
M$2 RXD \\$3 VDD \\$9 pfet L=0.28U W=40U AS=2P PS=9U
X$3 \\$3 VDD vsubs ppolyf_u_1k r=200000 L=400U W=2U
.ENDS
"""

# The same cell as `klt lvs` writes it under `options.keep_extracted`: the
# poly resistor becomes an `R` card whose value sits between nets and model.
LVS_KEPT_SPICE = LAYOUT_SPICE.replace(
    "X$3 \\$3 VDD vsubs ppolyf_u_1k r=200000 L=400U W=2U",
    "R$3 \\$3 VDD vsubs 200000 ppolyf_u_1k",
)


class DiscoverBlocks(unittest.TestCase):
    def test_discovers_from_gds_glob_sorted(self):
        with tempfile.TemporaryDirectory() as d:
            for name in ("zeta.gds", "alpha.gds", "mid.gds"):
                Path(d, name).write_bytes(b"")
            # Sibling files that are not streams must not become blocks.
            Path(d, "alpha.json").write_text("{}")
            Path(d, "notes.md").write_text("x")
            self.assertEqual(alvs.discover_blocks(d), ["alpha", "mid", "zeta"])

    def test_empty_dir_yields_no_blocks(self):
        with tempfile.TemporaryDirectory() as d:
            self.assertEqual(alvs.discover_blocks(d), [])

    def test_block_list_is_not_hard_coded(self):
        """A merged/renamed stream is picked up with no edit to the script."""
        with tempfile.TemporaryDirectory() as d:
            Path(d, "se_receiver_merged.gds").write_bytes(b"")
            self.assertEqual(alvs.discover_blocks(d), ["se_receiver_merged"])


class MissingReferenceFailsLoudly(unittest.TestCase):
    def test_missing_netlist_exits_nonzero_and_names_the_block(self):
        with tempfile.TemporaryDirectory() as d:
            gds_dir, net_dir, out_dir = (Path(d, x) for x in ("g", "n", "o"))
            for p in (gds_dir, net_dir, out_dir):
                p.mkdir()
            Path(gds_dir, "lonely.gds").write_bytes(b"")
            argv = ["analog_lvs.py", "--gds-dir", str(gds_dir),
                    "--netlist-dir", str(net_dir), "--out-dir", str(out_dir)]
            old = sys.argv
            sys.argv = argv
            try:
                with self.assertRaises(SystemExit) as cm:
                    alvs.main()
            finally:
                sys.argv = old
            msg = str(cm.exception)
            self.assertIn("lonely", msg)
            self.assertIn("missing reference netlist", msg)
            # Nothing was skipped silently: no artifacts were produced.
            self.assertEqual(list(out_dir.iterdir()), [])


class RequestShape(unittest.TestCase):
    def test_inline_layout_against_subckt_call_reference(self):
        req = alvs.lvs_request("demo")
        self.assertEqual(req["schema"], "klt.lvs.request/1")
        self.assertEqual(req["layout"],
                         {"file": "demo.gds", "deck": "gf180mcu", "top": "demo"})
        self.assertEqual(req["reference"], {
            "netlist": "demo_reference.spice",
            "top": "demo",
            "form": "subckt-call",
        })

    def test_paths_are_bare_relative_filenames(self):
        """Keeps the frozen report replayable from the artifacts directory."""
        req = alvs.lvs_request("demo")
        for path in (req["layout"]["file"], req["reference"]["netlist"]):
            self.assertFalse(os.path.isabs(path), path)
            self.assertNotIn("/", path, path)

    def test_only_option_is_output_side(self):
        """A mismatch is recorded, never tuned away (CLAUDE.md).

        `keep_extracted` is the single option set, and it only asks the tool
        to write out the netlist it already built -- it cannot change a
        verdict. Nothing that relaxes the compare may appear.
        """
        req = alvs.lvs_request("demo")
        self.assertEqual(req["options"], {"keep_extracted": True})
        blob = json.dumps(req)
        for knob in ("parameter_tolerance", "compare_parameters",
                     "flatten_layout", "flatten_reference", "ignore_mos_bulk",
                     "combine_devices", "netgen_setup"):
            self.assertNotIn(knob, blob)


class Classify(unittest.TestCase):
    def test_mos_families(self):
        self.assertEqual(alvs.classify("nfet"), "nfet")
        self.assertEqual(alvs.classify("nfet_03v3"), "nfet")
        self.assertEqual(alvs.classify("pfet"), "pfet")
        self.assertEqual(alvs.classify("pfet_03v3"), "pfet")

    def test_poly_resistor_is_not_a_pfet(self):
        """`ppolyf_u_1k` begins with "p" but is a three-terminal resistor."""
        self.assertEqual(alvs.classify("ppolyf_u_1k"), "other")
        self.assertEqual(alvs.classify("PPOLYF_U_1K"), "other")

    def test_unknown_and_none(self):
        self.assertEqual(alvs.classify(None), "other")
        self.assertEqual(alvs.classify("cap_mim_2f0"), "other")


class ParseSpice(unittest.TestCase):
    def _parse(self, text, top="demo"):
        with tempfile.TemporaryDirectory() as d:
            p = Path(d, "n.spice")
            p.write_text(text)
            return alvs.parse_spice_subckt(str(p), top)

    def test_reference_dialect_ports_and_bulk(self):
        ports, devs = self._parse(REFERENCE_SPICE)
        self.assertEqual(ports, ["VDD", "VSS", "DP", "RXD"])
        by = {d["name"]: d for d in devs}
        # Continuation lines are joined, so the parameter tail does not leak
        # into the net list.
        self.assertEqual(by["XMN_IN"]["nets"], ["RXD", "DP", "VSS", "VSS"])
        self.assertEqual(by["XMN_IN"]["model"], "nfet_03v3")
        self.assertEqual(by["XMP_LOAD"]["nets"], ["RXD", "IBIASN", "VDD", "VDD"])
        # The resistor has three terminals, not four.
        self.assertEqual(by["XRBIAS"]["nets"], ["IBIASN", "VDD", "VSS"])

    def test_extract_dialect_m_cards(self):
        ports, devs = self._parse(LAYOUT_SPICE)
        self.assertEqual(ports, ["VDD", "RXD", "vsubs"])
        by = {d["name"]: d for d in devs}
        self.assertEqual(by["M$1"]["nets"], ["RXD", "\\$5", "\\$1", "vsubs"])
        self.assertEqual(by["M$1"]["model"], "nfet")
        self.assertEqual(by["M$2"]["nets"], ["RXD", "\\$3", "VDD", "\\$9"])
        self.assertEqual(by["X$3"]["model"], "ppolyf_u_1k")

    def test_r_card_value_is_not_mistaken_for_a_net(self):
        """`R$3 \\$3 VDD vsubs 200000 ppolyf_u_1k` has three terminals."""
        _ports, devs = self._parse(LVS_KEPT_SPICE)
        by = {d["name"]: d for d in devs}
        self.assertEqual(by["R$3"]["nets"], ["\\$3", "VDD", "vsubs"])
        self.assertEqual(by["R$3"]["model"], "ppolyf_u_1k")
        self.assertNotIn("200000", by["R$3"]["nets"])

    def test_both_resistor_cardings_give_the_same_terminals(self):
        """`klt extract` (X card) and `klt lvs` (R card) must agree."""
        _p1, x_devs = self._parse(LAYOUT_SPICE)
        _p2, r_devs = self._parse(LVS_KEPT_SPICE)
        self.assertEqual({d["name"][1:]: d["nets"] for d in x_devs},
                         {d["name"][1:]: d["nets"] for d in r_devs})

    def test_is_number(self):
        for t in ("200000", "1.5e3", "2.2", "-3"):
            self.assertTrue(alvs._is_number(t), t)
        for t in ("VDD", "\\$3", "ppolyf_u_1k", "1k"):
            self.assertFalse(alvs._is_number(t), t)

    def test_other_subckts_are_ignored(self):
        text = REFERENCE_SPICE + "\n.subckt other A B\nXM1 A B A B nfet_03v3 m=1\n.ends\n"
        ports, devs = self._parse(text, "demo")
        self.assertEqual(ports, ["VDD", "VSS", "DP", "RXD"])
        self.assertNotIn("XM1", {d["name"] for d in devs})

    def test_anon_net_pattern(self):
        for name in ("\\$1", "$12", "\\$999"):
            self.assertTrue(alvs.ANON_NET_RE.match(name), name)
        for name in ("VSS", "vsubs", "AMPOUT", "NODE1", "TRIM0B"):
            self.assertFalse(alvs.ANON_NET_RE.match(name), name)


class AnalyzeCause(unittest.TestCase):
    def _cause(self):
        with tempfile.TemporaryDirectory() as d:
            lay, ref = Path(d, "l.spice"), Path(d, "r.spice")
            lay.write_text(LAYOUT_SPICE)
            ref.write_text(REFERENCE_SPICE)
            return alvs.analyze_cause("demo", str(lay), str(ref))

    def test_port_set_difference(self):
        c = self._cause()
        self.assertEqual(c["ports"]["only_in_layout"], ["vsubs"])
        self.assertEqual(c["ports"]["only_in_reference"], ["DP", "VSS"])
        self.assertEqual(c["ports"]["common"], ["RXD", "VDD"])

    def test_counts_unnamed_layout_nets(self):
        c = self._cause()
        self.assertEqual(c["layout_nets"]["unnamed"], ["\\$1", "\\$3", "\\$5", "\\$9"])
        self.assertEqual(c["layout_nets"]["unnamed_count"], 4)
        self.assertEqual(c["layout_nets"]["named"], ["RXD", "VDD", "vsubs"])

    def test_bulk_nets_per_class_both_sides(self):
        c = self._cause()
        self.assertEqual(c["bulk_nets"]["layout"],
                         {"nfet": ["vsubs"], "pfet": ["\\$9"]})
        self.assertEqual(c["bulk_nets"]["reference"],
                         {"nfet": ["VSS"], "pfet": ["VDD"]})

    def test_cause_is_identical_for_either_resistor_carding(self):
        with tempfile.TemporaryDirectory() as d:
            ref = Path(d, "r.spice"); ref.write_text(REFERENCE_SPICE)
            a, b = Path(d, "a.spice"), Path(d, "b.spice")
            a.write_text(LAYOUT_SPICE); b.write_text(LVS_KEPT_SPICE)
            self.assertEqual(alvs.analyze_cause("demo", str(a), str(ref)),
                             alvs.analyze_cause("demo", str(b), str(ref)))

    def test_resistor_excluded_from_bulk_comparison(self):
        """Three-terminal devices have no body terminal to compare."""
        c = self._cause()
        for side in ("layout", "reference"):
            self.assertNotIn("other", c["bulk_nets"][side])


if __name__ == "__main__":
    unittest.main(verbosity=2)
